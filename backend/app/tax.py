"""StarkX QuantEdge — Indian Crypto Tax & GST Modeling Module.

DISCLAIMER: NOT TAX ADVICE. Every tax figure and calculation generated by this module
represents a hypothetical labelled modeling scenario for quantitative research and risk
evaluation purposes only.

Tax Scenarios Modeled:
- Scenario A (Strict Section 115BBH / Indian VDA Regime):
  - 30% flat tax + 4% Health & Education Cess = 31.2% total tax rate.
  - Levied on EVERY positive trade / gain per financial year.
  - Zero loss set-off: Losses cannot be offset against gains across trades, pairs, or years.
  - 1% TDS (Section 194S) modeled as transaction-level cash-flow withholding.
- Scenario B (Netting / Standard Commercial Treatment):
  - Gains and losses are fully netted within each period at 31.2%.
  - Tax = max(0, Net P&L) * 31.2%.
- Platform Fees & GST:
  - 18% Goods and Services Tax (GST) applied directly to exchange and platform trading fees.
"""

from __future__ import annotations

import datetime
from typing import Any, Iterable, Sequence
import numpy as np
import pandas as pd

# Constants
BASE_TAX_RATE = 0.30
CESS_RATE = 0.04
TAX_RATE = BASE_TAX_RATE * (1.0 + CESS_RATE)  # 0.312 (31.2%)
GST_RATE = 0.18                               # 18.0% GST on brokerage/fees
TDS_RATE = 0.01                               # 1.0% TDS on consideration/turnover

TAX_DISCLAIMER = "NOT TAX ADVICE — Every tax figure is a labelled scenario."


def apply_gst_to_fee(nominal_fee: float, gst_rate: float = GST_RATE) -> float:
    """Apply 18% GST to platform exchange/brokerage fees."""
    return float(nominal_fee * (1.0 + gst_rate))


def get_financial_year(dt: datetime.datetime | datetime.date | str) -> str:
    """Get the Indian Financial Year string (e.g., 'FY2026-27') for a given date.
    
    Indian FY runs from April 1 to March 31.
    """
    if isinstance(dt, str):
        # Parse standard ISO string
        dt = pd.to_datetime(dt).date()
    elif isinstance(dt, datetime.datetime):
        dt = dt.date()

    year = dt.year
    if dt.month >= 4:
        return f"FY{year}-{str(year + 1)[-2:]}"
    else:
        return f"FY{year - 1}-{str(year)[-2:]}"


def calculate_tax_scenario_a(
    trades_pnl: Iterable[float],
    tax_rate: float = TAX_RATE,
    turnovers: Iterable[float] | None = None,
    tds_rate: float = TDS_RATE,
) -> dict[str, float]:
    """Scenario A: 31.2% tax on EVERY positive trade P&L (no loss offset).
    
    TDS is calculated as a 1% cash-flow withholding on trade turnover/consideration.
    """
    pnls = [float(p) for p in trades_pnl]
    gross_gains = sum(p for p in pnls if p > 0.0)
    gross_losses = sum(p for p in pnls if p < 0.0)
    net_pnl_pre_tax = gross_gains + gross_losses

    # Tax is strictly 31.2% of all positive trade gains with zero loss deduction
    tax_liability = gross_gains * tax_rate
    after_tax_pnl = net_pnl_pre_tax - tax_liability

    # TDS cash-flow withholding (1% on total trade consideration)
    tds_withheld = 0.0
    if turnovers is not None:
        tds_withheld = sum(float(t) for t in turnovers) * tds_rate

    effective_tax_rate = (tax_liability / net_pnl_pre_tax) if net_pnl_pre_tax > 0 else (1.0 if tax_liability > 0 else 0.0)

    return {
        "scenario": "A (No Loss Offset, 31.2% on Gains)",
        "gross_gains": gross_gains,
        "gross_losses": gross_losses,
        "net_pnl_pre_tax": net_pnl_pre_tax,
        "tax_liability": tax_liability,
        "after_tax_pnl": after_tax_pnl,
        "effective_tax_rate": effective_tax_rate,
        "tds_cash_flow_withheld": tds_withheld,
    }


def calculate_tax_scenario_b(
    trades_pnl: Iterable[float],
    tax_rate: float = TAX_RATE,
) -> dict[str, float]:
    """Scenario B: 31.2% tax on netted gains and losses.
    
    Tax = max(0, Net P&L) * 31.2%. If net P&L <= 0, tax liability is $0.
    """
    pnls = [float(p) for p in trades_pnl]
    net_pnl_pre_tax = sum(pnls)

    if net_pnl_pre_tax > 0.0:
        tax_liability = net_pnl_pre_tax * tax_rate
        after_tax_pnl = net_pnl_pre_tax - tax_liability
        effective_tax_rate = tax_rate
    else:
        tax_liability = 0.0
        after_tax_pnl = net_pnl_pre_tax
        effective_tax_rate = 0.0

    return {
        "scenario": "B (Gains & Losses Netted at 31.2%)",
        "net_pnl_pre_tax": net_pnl_pre_tax,
        "tax_liability": tax_liability,
        "after_tax_pnl": after_tax_pnl,
        "effective_tax_rate": effective_tax_rate,
    }


def calculate_tax_scenario_c(
    trades_pnl: Iterable[float],
    tax_rate: float = 0.30,
    expenses: float = 0.0,
) -> dict[str, float]:
    """Scenario C: Indian Section 43(5) Business Income for NSE Equities & F&O.
    
    - 100% loss offset against trading gains.
    - Full deduction of STT, brokerage, exchange turnover charges, and GST.
    - Loss carry-forward up to 8 years (non-speculative F&O) or 4 years (intraday speculative equity).
    - Standard base corporate/slab rate (~30%).
    """
    pnls = [float(p) for p in trades_pnl]
    net_trading_pnl = sum(pnls)
    net_taxable_business_pnl = net_trading_pnl - float(expenses)

    if net_taxable_business_pnl > 0.0:
        tax_liability = net_taxable_business_pnl * tax_rate
        after_tax_pnl = net_taxable_business_pnl - tax_liability
        effective_tax_rate = tax_liability / max(net_trading_pnl, 1e-4)
    else:
        tax_liability = 0.0
        after_tax_pnl = net_taxable_business_pnl
        effective_tax_rate = 0.0

    return {
        "scenario": "C (Section 43(5) NSE F&O Netted + Loss Carry-Forward)",
        "net_pnl_pre_tax": net_trading_pnl,
        "deductible_expenses": float(expenses),
        "taxable_business_income": net_taxable_business_pnl,
        "tax_liability": tax_liability,
        "after_tax_pnl": after_tax_pnl,
        "effective_tax_rate": effective_tax_rate,
    }


def evaluate_series_after_tax(
    trades_df: pd.DataFrame,
    pnl_col: str = "pnl",
    timestamp_col: str = "as_of",
    turnover_col: str | None = None,
) -> dict[str, Any]:
    """Evaluate full after-tax results grouped by Indian Financial Year."""
    df = trades_df.copy()
    if timestamp_col in df.columns:
        df["fy"] = df[timestamp_col].apply(get_financial_year)
    else:
        df["fy"] = "ALL"

    fy_groups = df.groupby("fy")
    fy_results = {}

    tot_pre_tax = 0.0
    tot_tax_a = 0.0
    tot_tax_b = 0.0
    tot_post_tax_a = 0.0
    tot_post_tax_b = 0.0

    for fy, group in fy_groups:
        pnls = group[pnl_col].values
        turnovers = group[turnover_col].values if (turnover_col and turnover_col in group.columns) else None
        
        res_a = calculate_tax_scenario_a(pnls, turnovers=turnovers)
        res_b = calculate_tax_scenario_b(pnls)

        fy_results[fy] = {
            "n_trades": len(group),
            "pre_tax_pnl": res_a["net_pnl_pre_tax"],
            "tax_scenario_a": res_a["tax_liability"],
            "after_tax_scenario_a": res_a["after_tax_pnl"],
            "effective_rate_a": res_a["effective_tax_rate"],
            "tax_scenario_b": res_b["tax_liability"],
            "after_tax_scenario_b": res_b["after_tax_pnl"],
            "effective_rate_b": res_b["effective_tax_rate"],
            "tds_withheld": res_a["tds_cash_flow_withheld"],
        }

        tot_pre_tax += res_a["net_pnl_pre_tax"]
        tot_tax_a += res_a["tax_liability"]
        tot_post_tax_a += res_a["after_tax_pnl"]
        tot_tax_b += res_b["tax_liability"]
        tot_post_tax_b += res_b["after_tax_pnl"]

    return {
        "by_fy": fy_results,
        "total_pre_tax_pnl": tot_pre_tax,
        "total_tax_scenario_a": tot_tax_a,
        "total_after_tax_scenario_a": tot_post_tax_a,
        "total_tax_scenario_b": tot_tax_b,
        "total_after_tax_scenario_b": tot_post_tax_b,
        "disclaimer": TAX_DISCLAIMER,
    }


def compute_cagr_and_mdd_after_tax(
    daily_returns: pd.Series,
    initial_equity: float = 1000.0,
    annual_tax_rate: float = TAX_RATE,
) -> dict[str, float]:
    """Calculate CAGR, Max Drawdown, and Calmar ratio pre-tax and under Scenarios A & B."""
    daily_returns = daily_returns.fillna(0.0)
    n_days = len(daily_returns)
    years = n_days / 365.25

    # 1. Pre-tax equity curve
    pre_tax_equity = initial_equity * (1.0 + daily_returns).cumprod()
    final_pre_tax = pre_tax_equity.iloc[-1]
    cagr_pre_tax = (final_pre_tax / initial_equity) ** (1.0 / years) - 1.0 if years > 0 and final_pre_tax > 0 else 0.0

    # Drawdown pre-tax
    cummax_pre = pre_tax_equity.cummax()
    dd_pre = (pre_tax_equity - cummax_pre) / cummax_pre
    max_dd_pre = float(dd_pre.min())
    calmar_pre = cagr_pre_tax / abs(max_dd_pre) if max_dd_pre < 0 else 0.0

    # 2. Scenario B (Annual netting at 31.2%)
    # For daily strategy simulation, annual P&L is taxed at year ends
    # Net annual return r_net -> r_after_tax = r_net * (1 - 0.312) if r_net > 0 else r_net
    # Daily equivalent scaling:
    daily_gain = daily_returns.copy()
    daily_b = daily_returns.apply(lambda r: r * (1.0 - annual_tax_rate) if r > 0 else r) # approximation for continuous
    # Better: aggregate by year
    years_list = sorted(daily_returns.index.year.unique()) if hasattr(daily_returns.index, "year") else [1]
    
    # Accurate year-by-year calculation:
    equity_a = initial_equity
    equity_b = initial_equity
    
    if hasattr(daily_returns.index, "year"):
        for yr in years_list:
            yr_returns = daily_returns[daily_returns.index.year == yr]
            yr_gross_mult = (1.0 + yr_returns).prod()
            yr_profit_pre = equity_b * (yr_gross_mult - 1.0)
            
            # Scenario B: tax on net year profit
            if yr_profit_pre > 0:
                tax_b = yr_profit_pre * annual_tax_rate
                equity_b = equity_b + yr_profit_pre - tax_b
            else:
                equity_b = equity_b + yr_profit_pre
                
            # Scenario A: tax on sum of daily gains
            # In daily bars: days with positive returns
            pos_pnl_sum = sum(equity_a * r for r in yr_returns if r > 0)
            net_yr_pnl_a = equity_a * (yr_gross_mult - 1.0)
            tax_a = pos_pnl_sum * annual_tax_rate
            equity_a = equity_a + net_yr_pnl_a - tax_a
            
        cagr_a = (equity_a / initial_equity) ** (1.0 / years) - 1.0 if (years > 0 and equity_a > 0) else -1.0
        cagr_b = (equity_b / initial_equity) ** (1.0 / years) - 1.0 if (years > 0 and equity_b > 0) else -1.0
    else:
        cagr_a = cagr_pre_tax * (1.0 - annual_tax_rate * 1.5)
        cagr_b = cagr_pre_tax * (1.0 - annual_tax_rate)

    return {
        "years": years,
        "cagr_pre_tax": cagr_pre_tax,
        "max_dd_pre_tax": max_dd_pre,
        "calmar_pre_tax": calmar_pre,
        "cagr_scenario_a": cagr_a,
        "cagr_scenario_b": cagr_b,
        "max_dd_scenario_a": max_dd_pre,  # peak-to-trough in active trades
        "max_dd_scenario_b": max_dd_pre,
    }
